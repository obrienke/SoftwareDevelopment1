public class PrimTypes {
    public static void main(String[] args) {
        boolean check = true;
        char c = 'f';
        byte b = 10;
        short s = 20100;
        int i = 1_000_000;
        long l = 3000_000_000L;
        float f = 2.5f;
        double dec = 2.5;

        String div = "---------------------------------";

        System.out.println(div);
        System.out.println("|Type\t\t|Example\t|");
        System.out.println(div);
        System.out.println("|boolean\t|"+check+"\t\t|");
        System.out.println(div);
        System.out.println("|char\t\t|"+c+"\t\t|");
        System.out.println(div);
        System.out.println("|byte\t\t|"+b+"\t\t|");
        System.out.println(div);
        System.out.println("|short\t\t|"+s+"\t\t|");
        System.out.println(div);
        System.out.println("|int\t\t|"+i+"\t|");
        System.out.println(div);
        System.out.println("|long\t\t|"+l+"\t|");
        System.out.println(div);
        System.out.println("|float\t\t|"+f+"\t\t|");
        System.out.println(div);
        System.out.println("|double\t\t|"+dec+"\t\t|");
        System.out.println(div);
    }
}
