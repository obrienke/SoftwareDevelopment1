public class FirstIfs {
    public static void main(String[] args) {
        int x = 0;

        if(x == 1){
            System.out.println("is equal to 1");
        }
        if(x != 1){
            System.out.println("is not equal to 1");
        }
        if(x > 1){
            System.out.println("is greater than 1");
        }
        if(x < 1){
            System.out.println("is less than 1");
        }
    }
}
